/** Minimal environment for pi/omp children; provider tokens are explicit exceptions, never patterns. */
export function childEnv(source: NodeJS.ProcessEnv = process.env): NodeJS.ProcessEnv {
	return Object.fromEntries(Object.entries(source).filter(([key, value]) => value !== undefined
		&& (ALLOWED.has(key) || key.startsWith("PSI_") || key.startsWith("LC_"))));
}
